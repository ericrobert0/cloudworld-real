import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
import {ROOT} from '../infra.mjs';
import {distributionFiles} from '../distribution.mjs';
const pkg=JSON.parse(fs.readFileSync(path.join(ROOT,'package.json'))),dir=path.join(ROOT,'releases');fs.mkdirSync(dir,{recursive:true});
const file=path.join(dir,`cloudworld-${pkg.version}-${new Date().toISOString().slice(0,10)}.tar.gz`);
const files=distributionFiles(ROOT);
await new Promise((resolve,reject)=>{const p=spawn('tar',['-czf',file,'-C',ROOT,...files],{windowsHide:true,stdio:['ignore','ignore','pipe']});let err='';p.stderr.on('data',d=>err+=d);p.on('error',reject);p.on('close',c=>c===0?resolve():reject(Error('Empacotamento falhou: '+err.slice(-500))));});
const hash=crypto.createHash('sha256');for await(const chunk of fs.createReadStream(file))hash.update(chunk);fs.writeFileSync(file+'.sha256',hash.digest('hex')+'  '+path.basename(file)+'\n');
console.log('Pacote de fontes criado, sem runtime, senhas, backups ou node_modules: '+file);
